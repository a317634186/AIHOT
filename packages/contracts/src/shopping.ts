export function brandSlug(value: string): string {
  return value
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/['’]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

export function resolveBrandBySlug(
  slug: string,
  catalogBrands?: Array<{ key: string; label: string; count?: number }>,
): { key: string; label: string } | null {
  const clean = slug.trim().toLowerCase();
  if (!clean || !/^[a-z0-9-]{2,64}$/.test(clean)) return null;
  const fromKnown = KNOWN_BRANDS.find((name) => brandSlug(name) === clean);
  if (fromKnown) return { key: fromKnown.toLowerCase(), label: fromKnown };
  const fromCatalog = catalogBrands?.find((b) => brandSlug(b.label) === clean || brandSlug(b.key) === clean);
  if (fromCatalog) return { key: fromCatalog.key, label: fromCatalog.label };
  if (catalogBrands === undefined) {
    const fallbackLabel = clean.split('-').filter(Boolean).map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
    return { key: clean, label: fallbackLabel || clean };
  }
  return null;
}

const REAL_ARTICLE_ID_RE = /^[a-z0-9]{20,32}$/;
const ITEM_ROUTE_ID_RE = /^[a-z0-9][a-z0-9-]{1,79}$/;
const SLUG_STOP_WORDS = new Set([
  'for','with','code','promo','coupon','the','and','from','off','sale','deal','offer','at','on','in','to','up',
]);

export function itemSlug(input: {
  title: string;
  offer?: Partial<Pick<Offer, 'brand' | 'product' | 'model' | 'merchant'>>;
}): string {
  const d = input.offer;
  const primary = (d?.product?.trim() || d?.model?.trim() || input.title)
    .replace(/\b(?:for|at|from)\s+\$[\d,.]+.*$/i, '')
    .replace(/\$[\d,.]+/g, ' ');
  const parts = [d?.brand, primary, d?.merchant].filter((x): x is string => Boolean(x?.trim()));
  const tokens: string[] = [];
  const seen = new Set<string>();
  for (const part of parts) {
    const words = part
      .normalize('NFKD')
      .replace(/[\u0300-\u036f]/g, '')
      .replace(/['’]/g, '')
      .toLowerCase()
      .split(/[^a-z0-9]+/)
      .filter((w) => w.length >= 2 && !SLUG_STOP_WORDS.has(w));
    for (const w of words) {
      if (seen.has(w)) continue;
      seen.add(w);
      tokens.push(w);
    }
  }
  let slug = '';
  for (const token of tokens) {
    const next = slug ? `${slug}-${token}` : token;
    if (next.length > 64) break;
    slug = next;
  }
  return slug;
}

/** Canonical keyword-rich item path. Bare IDs and stale slugs resolve to this path. */
export function itemPath(input: {
  id: string;
  title: string;
  offer?: Partial<Pick<Offer, 'brand' | 'product' | 'model' | 'merchant'>>;
}): string {
  if (!REAL_ARTICLE_ID_RE.test(input.id)) return `/items/${input.id}`;
  const slug = itemSlug(input);
  return slug ? `/items/${slug}--${input.id}` : `/items/${input.id}`;
}

/** Extracts an article ID from canonical and legacy slug-prefixed item routes. */
export function parseItemRouteSegment(segment: string): string {
  const semanticSeparator = segment.lastIndexOf('--');
  if (semanticSeparator > 0) {
    const tail = segment.slice(semanticSeparator + 2);
    if (ITEM_ROUTE_ID_RE.test(tail)) return tail;
  }
  const separator = segment.lastIndexOf('-');
  if (separator > 0) {
    const tail = segment.slice(separator + 1);
    if (REAL_ARTICLE_ID_RE.test(tail)) return tail;
  }
  return segment;
}

