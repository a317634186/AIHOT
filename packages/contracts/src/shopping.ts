/** Shorten public copy without leaving a partial final word in HTML or metadata. */
export function truncateAtWord(value: string, maxLength: number): string {
  const clean = String(value ?? '').replace(/\s+/g, ' ').trim();
  const limit = Math.floor(maxLength);
  if (!clean || !Number.isFinite(limit) || limit < 1 || clean.length <= limit) return clean;

  const contentLimit = Math.max(1, limit - 1);
  let boundary = clean.lastIndexOf(' ', contentLimit);
  if (boundary <= 0) {
    // Keep an unusually long first token intact instead of cutting inside it.
    boundary = clean.indexOf(' ', contentLimit);
    if (boundary < 0) return clean;
  }
  const prefix = clean.slice(0, boundary).trimEnd();
  return prefix ? `${prefix}…` : clean;
}

