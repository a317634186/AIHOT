function cleanSeoSellingPoint(item:SeoDescriptionItem):string{
  const d=item.offer;
  const candidates=[
    d.aiOverview?.highlights?.[0],
    d.review?.verdict,
    d.review?.strengths?.[0],
    d.aiOverview?.summary,
    item.summary,
  ];
  for(const raw of candidates){
    if(!raw)continue;
    const stripped=raw
      .replace(/<[^>]*>/g,' ')
      .replace(/\b(?:confirm|check)\s+the\s+(?:exact\s+configuration|source|retailer|current\s+price)[^.!?]*[.!?]?/gi,' ')
      .replace(/\b(?:the\s+(?:source|reported)\s+price\s+or\s+coupon\s+details\s+need\s+review|checking\s+the\s+retailer\s+for\s+its\s+current\s+price)[^.!?]*[.!?]?/gi,' ')
      .replace(/\b(?:the\s+(?:source\s+reports|retailer\s+lists)|this\s+offer\s+concerns)\b[^.!?]*[.!?]?/gi,' ')
      .replace(/^[^.!?]*\bis\s+currently\s+listed\s+at\s+\$[\d,.]+[^.!?]*[.!?]?\s*/i,'')
      .replace(/^the\s+former\s+deal\s+price\s+is\s+(?:no\s+longer\s+listed|kept\s+as\s+a\s+historical\s+reference)[^.!?]*[.!?]?\s*/i,'')
      .replace(/\s+/g,' ')
      .trim();
    const first=stripped.split(/(?<=[.!?])\s+/)[0]?.trim()??'';
    if(first.length>=18)return /[.!?]$/.test(first)?first:first+'.';
  }
  return '';
}

function couponAndDeadlineSeoTail(item:SeoDescriptionItem):string{
  const d=item.offer;
  if(isCalibratedRegularPrice(d))return '';
  const parts:string[]=[];
  const coupon=d.coupon?.trim()??'';
  if(coupon){
    const code=/^[A-Z0-9_-]{3,28}$/i.test(coupon)?coupon:coupon.match(/\b(?:code|coupon)\s*[:\"']?\s*([A-Z0-9_-]{4,28})\b/i)?.[1]??coupon.match(/\b(?=[A-Z0-9]{5,24}\b)(?=[A-Z0-9]*\d)[A-Z0-9]+\b/)?.[0];
    parts.push(code?`Code ${code}`:/\bclip\b/i.test(coupon)?'Clip on-page coupon':'Coupon available');
  }
  if(item.timing?.endsDay){
    const day=new Date(item.timing.endsDay+'T12:00:00Z');
    if(Number.isFinite(day.getTime()))parts.push('Ends '+new Intl.DateTimeFormat('en-US',{month:'short',day:'numeric',timeZone:'UTC'}).format(day));
  }else if(d.expiresAt&&Number.isFinite(Date.parse(d.expiresAt))){
    parts.push('Ends '+new Intl.DateTimeFormat('en-US',{month:'short',day:'numeric',timeZone:SHOPPING.timeZone}).format(new Date(d.expiresAt)));
  }else if(d.deadlineOriginal&&d.deadlineOriginal.trim().length<=28){
    parts.push(d.deadlineOriginal.trim().replace(/[.]+$/,''));
  }
  return parts.length?parts.join(' · ')+'.':'';
}

